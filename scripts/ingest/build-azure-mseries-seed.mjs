#!/usr/bin/env node
/**
 * build-azure-mseries-seed.mjs — regenerate the Azure M-Series seed's
 * regional availability + rates from the live ingested shards.
 *
 * WHY: the hand-built M-Series seed (azureMSeriesSeed.ts) shipped its sizes
 * across only 6 hard-coded regions via AZURE_REGION_MULTIPLIERS, with rates
 * derived by multiplier guesses. The Session-36 live ingest proved M-Series
 * is actually published in ~54 Azure regions, and the shards carry REAL
 * PAYG / 1yr / 3yr rates. This script reads those shards and emits
 * `src/data/azureMSeriesSeedRates.json` keyed by DISPLAY region → SKU →
 * {payg, ri1y, ri3y}, so the seed expands across the true footprint with
 * accurate, non-fabricated rates.
 *
 * The TS seed restricts to its curated M_SERIES_SPECS SKU set via a join,
 * so this file can safely emit every live M-series SKU it finds.
 *
 * Region naming: shards are keyed by slug (eastus2); the catalog elsewhere
 * uses display names (East US 2). We map slug→display by matching the
 * normalized slug against the catalog's canonical display-region set
 * (DISPLAY_REGIONS below). Shard regions that don't match a known display
 * name (gov-edge / AT&T / Delos sovereign / brand-new slugs) are skipped so
 * M-series stays within the same region universe as every other family.
 *
 * Run:  node scripts/ingest/build-azure-mseries-seed.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '../..');
const SHARD_DIR = resolve(ROOT, 'public/rates/azure');
const OUT = resolve(ROOT, 'src/data/azureMSeriesSeedRates.json');

/** Canonical Azure display-region set — the names every other family in the
 *  catalog already uses. Kept in sync with the seed's region universe. */
const DISPLAY_REGIONS = [
  'Australia Central', 'Australia Central 2', 'Australia East', 'Australia Southeast',
  'Austria East', 'Belgium Central', 'Brazil South', 'Brazil Southeast',
  'Canada Central', 'Canada East', 'Central India', 'Central US', 'Chile Central',
  'Denmark East', 'East Asia', 'East US', 'East US 2', 'France Central', 'France South',
  'Germany North', 'Germany West Central', 'India Central', 'Indonesia Central',
  'Israel Central', 'Italy North', 'Japan East', 'Japan West', 'Korea Central',
  'Korea South', 'Malaysia West', 'Mexico Central', 'New Zealand North',
  'North Central US', 'North Europe', 'Norway East', 'Norway West', 'Poland Central',
  'Qatar Central', 'South Africa North', 'South Africa West', 'South Central US',
  'South India', 'Southeast Asia', 'Spain Central', 'Sweden Central', 'Sweden South',
  'Switzerland North', 'Switzerland West', 'UAE Central', 'UAE North', 'UK South',
  'UK West', 'US Gov Arizona', 'US Gov Texas', 'US Gov Virginia', 'West Central US',
  'West Europe', 'West India', 'West US', 'West US 2', 'West US 3',
  // v2.25.2 — real high-coverage regions the live shards carry that the seed
  // previously omitted (Jio India West 1190 SKUs, Jio India Central 1010,
  // Israel Northwest 924, India South Central 588). M-series picks each up
  // only where the shard actually has M-series SKUs (data-driven).
  'Jio India West', 'Jio India Central', 'Israel Northwest', 'India South Central',
];

const norm = (s) => (s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const slugToDisplay = new Map(DISPLAY_REGIONS.map((d) => [norm(d), d]));

/** M-series SKU: Standard_M followed by a digit (M8ms, M128ms, M416s_v2 …). */
const isMSeriesSku = (sku) => /^Standard_M\d/.test(sku);

const shardFiles = readdirSync(SHARD_DIR).filter(
  (f) => f.endsWith('.json') && !f.startsWith('_'),
);

const regions = {};
const unmatchedSlugs = [];
let totalRows = 0;

for (const file of shardFiles) {
  const slug = file.replace(/\.json$/, '');
  const display = slugToDisplay.get(norm(slug));
  const rates = JSON.parse(readFileSync(resolve(SHARD_DIR, file), 'utf8'));
  const mSkus = Object.keys(rates).filter(isMSeriesSku);
  if (mSkus.length === 0) continue; // region has no M-series
  if (!display) {
    unmatchedSlugs.push(`${slug} (${mSkus.length} M-series SKUs)`);
    continue;
  }
  const bucket = (regions[display] ??= {});
  for (const sku of mSkus) {
    const r = rates[sku];
    if (!r || typeof r.payg !== 'number') continue;
    bucket[sku] = {
      payg: r.payg,
      ri1y: typeof r.ri1y === 'number' ? r.ri1y : null,
      ri3y: typeof r.ri3y === 'number' ? r.ri3y : null,
    };
    totalRows++;
  }
}

const out = {
  _comment:
    'GENERATED by scripts/ingest/build-azure-mseries-seed.mjs from public/rates/azure/. ' +
    'Real Azure Retail Prices per region. Do not hand-edit; re-run the script.',
  asOf: new Date().toISOString().slice(0, 10),
  source: 'public/rates/azure/<region>.json (Azure Retail Prices API)',
  regions,
};

writeFileSync(OUT, JSON.stringify(out, null, 0) + '\n');

// ── Report ────────────────────────────────────────────────────────────────
const regionCount = Object.keys(regions).length;
const skuUnion = new Set();
for (const b of Object.values(regions)) for (const s of Object.keys(b)) skuUnion.add(s);
console.log(`Azure M-series seed rates → ${OUT.replace(ROOT + '/', '')}`);
console.log(`  regions written : ${regionCount} (display-mapped)`);
console.log(`  distinct M SKUs : ${skuUnion.size}`);
console.log(`  region×sku rows : ${totalRows}`);
if (unmatchedSlugs.length) {
  console.log(`  skipped (no display-name match): ${unmatchedSlugs.length}`);
  for (const u of unmatchedSlugs) console.log(`    - ${u}`);
}
